/**
 * Regenerates src/components/horizon/icon/names.ts from the installed lucide-react.
 *
 * `IGRPIconObject` (the list of icon names, used by pickers and Storybook
 * controls) must not import lucide's `icons` object: that pulls every icon's
 * code, and because `IGRPIcon` lazy-loads icons one per chunk, a bundler then
 * emits ~1,700 chunk requests for anything importing the list. So the names are
 * committed as data. `src/components/horizon/icon/__tests__/names.test.ts` fails
 * whenever they drift from lucide — run `pnpm generate:icon-names` to fix it.
 */
import { writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import { icons } from "lucide-react"

const target = fileURLToPath(new URL("../src/components/horizon/icon/names.ts", import.meta.url))
const names = Object.keys(icons).sort()

const source = `// GENERATED by scripts/generate-icon-names.mjs — do not edit by hand.
// Regenerate after bumping lucide-react: \`pnpm generate:icon-names\`.

/** Every lucide icon name (PascalCase), sorted. Data only — no icon code. */
export const IGRP_ICON_NAMES: readonly string[] = ${JSON.stringify(names)}
`

await writeFile(target, source)
console.log(`wrote ${names.length} icon names to ${target}`)
